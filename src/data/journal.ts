export function arcNoteFor(series: string, arc: number, arcs: { id: string }[]): ArcNote | undefined {
  const id = arcs[arc]?.id;
  if (!id) return undefined;
  return ARC_NOTES.find((n) => n.series === series && n.arc === id);
}
