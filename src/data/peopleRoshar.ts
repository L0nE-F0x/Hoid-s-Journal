import type { Character } from './types.ts';

const C = 'canon' as const;

const R3: Character['eras'] = [{ era: 3, system: 'rosharan', body: 'roshar' }];
const R15: Character['eras'] = [1, 2, 3, 4, 5].map((era) => ({ era, system: 'rosharan', body: 'roshar' }));
const R13: Character['eras'] = [1, 2, 3].map((era) => ({ era, system: 'rosharan', body: 'roshar' }));

function ch(
  id: string, name: string, color: string, book: string, origin: string,
  aliases: string, abilities: string, fact: string, cognitive: boolean,
  eras: Character['eras'],
  extra: Partial<Character> = {},
): Character {
  // Each person gets their own copy of the trail. R3 and friends are shared
  // constants, and data/index.ts pushes presence beats onto `eras` in place:
  // without the copy, one person standing in Shinovar puts everyone there.
  const own = eras.map((row) => ({ ...row }));
  return { id, name, color, book, origin, aliases, abilities, fact, cognitive, eras: own, canon: extra.canon ?? C, sources: extra.sources ?? [book], ...extra };
}

